#!/usr/bin/env python3
"""Generate compact display-name lookup keys from the English UI resources.

The English table stays in ui_strings.def for a future language switch. Phase 2
needs only hashes to map existing protocol descriptor names to Japanese IDs.
"""
import re
import sys
from pathlib import Path


def fnv1a(value):
    h = 2166136261
    for b in value.encode("utf-8"):
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


src = Path(__file__).resolve().parents[1] / "firmware/src/ui_strings.def"
entries = re.findall(r'^UI_STRING\(([^,]+),\s*"([^"]*)",\s*"([^"]*)"\)', src.read_text(), re.M)
assert entries
values = [fnv1a(en) for _, en, _ in entries]
distinct = {}
for (name, en, _), key in zip(entries, values):
    if key in distinct and distinct[key] != en:
        raise SystemExit(f"UI string hash collision: {name} / {distinct[key]}")
    distinct[key] = en
blob = bytearray()
offsets = []
known = {}
for _, _, ja in entries:
    if ja not in known:
        known[ja] = len(blob)
        blob.extend(ja.encode("utf-8") + b"\0")
    offsets.append(known[ja])
assert len(blob) < 65536
lines = ["/* generated by tools/gen_ui_hash.py; aligned with ui_strings.def */",
         "#pragma once", f"static const uint8_t UI_JA_BLOB[{len(blob)}] = {{"]
for i in range(0, len(blob), 24):
    lines.append("    " + ", ".join(f"0x{x:02x}" for x in blob[i:i + 24]) + ",")
lines += ["};", f"static const uint16_t UI_JA_OFF[{len(offsets)}] = {{"]
for i in range(0, len(offsets), 16):
    lines.append("    " + ", ".join(map(str, offsets[i:i + 16])) + ",")
lines += ["};", f"static const uint32_t UI_EN_HASH[{len(values)}] = {{"]
for i in range(0, len(values), 8):
    lines.append("    " + ", ".join(f"0x{x:08x}u" for x in values[i:i + 8]) + ",")
lines += ["};", ""]
Path(sys.argv[1]).write_text("\n".join(lines))
print(f"UI resources: {len(values)} IDs, {len(blob)} B JA text, {len(known)} unique JA strings, EN hashes")
